#!/usr/bin/env python3
"""Exact authored finite-law example for longitudinal banking policies.

This is a g-formula truth oracle, not an ltmle package execution. It uses
fractions and exhaustive path enumeration so that policy targets and the
decision-layer monetary consequences are exactly reproducible.
"""
from fractions import Fraction as F
import json
from pathlib import Path


P_HIGH_RISK = F(1, 3)


def p_h(h):
    return P_HIGH_RISK if h else 1 - P_HIGH_RISK


def p_hardship(h, a0):
    return {
        (0, 0): F(1, 4),
        (0, 1): F(1, 8),
        (1, 0): F(3, 4),
        (1, 1): F(1, 2),
    }[(h, a0)]


def policies(h, l1):
    return {
        "status_quo": (0, 0),
        "targeted_dynamic": (h, l1),
        "broad_contact": (1, 1),
    }


def p_default(h, a0, l1, a1):
    return F(1, 20) + F(h, 10) + F(l1, 5) - F(a0, 25) - F(a1, 20)


def calculate():
    results = {}
    for name in ("status_quo", "targeted_dynamic", "broad_contact"):
        default_risk = F(0)
        uncensored = F(0)
        contacts = [F(0), F(0)]
        path_count = 0
        for h in (0, 1):
            a0, _ = policies(h, 0)[name]
            p_l1_one = p_hardship(h, a0)
            for l1 in (0, 1):
                p_l1 = p_l1_one if l1 else 1 - p_l1_one
                _, a1 = policies(h, l1)[name]
                path_probability = p_h(h) * p_l1
                path_count += 1
                default_risk += path_probability * p_default(h, a0, l1, a1)
                p_observed = F(3, 4) if l1 else F(9, 10)
                uncensored += path_probability * p_observed
                contacts[0] += path_probability * a0
                contacts[1] += path_probability * a1
        contact_cost = 6 * contacts[0] + 4 * contacts[1]
        results[name] = {
            "policy_rule": {
                "status_quo": "A0=0; A1=0",
                "targeted_dynamic": "A0=H; A1=L1",
                "broad_contact": "A0=1; A1=1",
            }[name],
            "default_probability": str(default_risk),
            "uncensored_probability": str(uncensored),
            "expected_contacts": [str(x) for x in contacts],
            "expected_contact_cost_usd": str(contact_cost),
            "expected_default_loss_usd": str(1000 * default_risk),
            "path_count": path_count,
        }
    base = F(results["status_quo"]["default_probability"])
    for name, value in results.items():
        risk = F(value["default_probability"])
        cost = F(value["expected_contact_cost_usd"])
        value["avoided_default_loss_vs_status_quo_usd"] = str(1000 * (base - risk))
        value["net_value_vs_status_quo_usd"] = str(1000 * (base - risk) - cost)
    return {
        "status": "exact_authored_truth_oracle_not_native_software_execution",
        "currency": "USD per account over two monthly servicing periods",
        "law": {
            "P_H1": "1/3",
            "P_L1_1_given_H_A0": {
                "H0_A00": "1/4",
                "H0_A01": "1/8",
                "H1_A00": "3/4",
                "H1_A01": "1/2",
            },
            "P_default_given_H_A0_L1_A1": "1/20 + H/10 + L1/5 - A0/25 - A1/20",
            "P_uncensored_given_L1": {"L1_0": "9/10", "L1_1": "3/4"},
            "default_cost_usd": 1000,
            "contact_cost_usd": {"month_1": 6, "month_2": 4},
        },
        "formula": "sum_h,l P(h) P(l|h,A0=d0(h)) E[Y|h,A0=d0(h),l,A1=d1(l)]",
        "results": results,
        "paired_target_contrasts": {
            "targeted_minus_status_quo_default_risk": str(
                F(results["targeted_dynamic"]["default_probability"])
                - F(results["status_quo"]["default_probability"])),
            "broad_minus_status_quo_default_risk": str(
                F(results["broad_contact"]["default_probability"])
                - F(results["status_quo"]["default_probability"])),
            "uncertainty": "Not estimated. Package output, influence-curve covariance, censoring adjustment, support and finite-sample coverage are not represented by this truth calculation.",
        },
        "assumptions_and_limits": [
            "All histories, treatment actions, hardship, default and censoring are generated by the stipulated law; this is synthetic mathematical evidence.",
            "The independent unit is an account. Clustered accounts require a cluster sampling law and cluster-level uncertainty calculation.",
            "Censoring is conditionally independent of future default given the listed history, with uncensoring probabilities bounded below by 3/4; this positivity statement is specific to this law.",
            "These policy means are g-formula truth targets; no ltmle or other estimator was run, so there is no qualification claim.",
        ],
    }


if __name__ == "__main__":
    output = calculate()
    target = Path("docs/program/execution/2026-10-23/ltmle-reuse-v1/policy-oracle-results.json")
